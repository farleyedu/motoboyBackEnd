-- Zippy Social R14: máquinas com o zippy-render, pareamento por código de 6 dígitos, fila de trabalhos e registro de uso.
-- Contrato: zippy-admin/docs/zippy-social/prompts/editor-real/R14-CONTRATO-FILA.md.
-- Mesma row-level security das outras tabelas social_* (zippy.loja / zippy.sistema). Quem vê o quê DENTRO da loja
-- (a máquina é de quem pareou, salvo se compartilhada) é filtrado nas consultas do backend. Idempotente.
BEGIN;

CREATE TABLE IF NOT EXISTS social_maquinas (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    usuario_id      integer NOT NULL,          -- dono: quem gerou o código de pareamento
    tipo            text NOT NULL DEFAULT 'worker' CHECK (tipo IN ('worker', 'navegador')),
    dispositivo_id  text NOT NULL,
    nome            text NOT NULL,
    token_hash      text,                      -- SHA-256 do token; NULL = removida
    compartilhada_equipe boolean NOT NULL DEFAULT FALSE,
    ativa           boolean NOT NULL DEFAULT TRUE,
    pausada_por_plano boolean NOT NULL DEFAULT FALSE,
    usa_gpu         boolean NOT NULL DEFAULT FALSE,
    gpu             text,
    espaco_livre    bigint,
    versao          text,
    ultimo_sinal_em timestamptz,
    criado_em       timestamptz NOT NULL DEFAULT NOW(),
    removida_em     timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_maquinas_dispositivo ON social_maquinas (estabelecimento_id, usuario_id, dispositivo_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_maquinas_token ON social_maquinas (token_hash) WHERE token_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS social_pareamentos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    codigo          text NOT NULL CHECK (codigo ~ '^[0-9]{6}$'),
    gerado_por_usuario_id integer NOT NULL,
    expira_em       timestamptz NOT NULL,
    usado_em        timestamptz,
    usado_por_maquina_id bigint REFERENCES social_maquinas(id) ON DELETE SET NULL,
    criado_em       timestamptz NOT NULL DEFAULT NOW()
);
-- um código em aberto não se repete entre lojas: quem pareia só informa o código
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_pareamentos_aberto ON social_pareamentos (codigo) WHERE usado_em IS NULL;

CREATE TABLE IF NOT EXISTS social_trabalhos (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    tipo            text NOT NULL CHECK (tipo IN ('renderizar')),
    maquina_id      bigint NOT NULL REFERENCES social_maquinas(id) ON DELETE CASCADE,
    pedido_por_usuario_id integer NOT NULL,
    alvo_tipo       text NOT NULL,
    alvo_id         uuid NOT NULL,             -- renderizar: social_renders.id
    payload         jsonb NOT NULL,            -- foto do pedido; as URLs dos arquivos são assinadas só na entrega
    status          text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'rodando', 'concluido', 'falhou', 'cancelado')),
    progresso       numeric(5,2) NOT NULL DEFAULT 0 CHECK (progresso >= 0 AND progresso <= 100),
    tentativas      integer NOT NULL DEFAULT 0,
    erro            text,
    resultado       jsonb,
    chave_idempotencia text NOT NULL,
    criado_em       timestamptz NOT NULL DEFAULT NOW(),
    iniciado_em     timestamptz,
    sinal_em        timestamptz,               -- último sinal da máquina sobre ESTE trabalho
    concluido_em    timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_trabalhos_chave ON social_trabalhos (estabelecimento_id, chave_idempotencia)
    WHERE status IN ('pendente', 'rodando');
CREATE INDEX IF NOT EXISTS ix_social_trabalhos_maquina ON social_trabalhos (maquina_id, status, criado_em);
CREATE INDEX IF NOT EXISTS ix_social_trabalhos_alvo ON social_trabalhos (alvo_id);

CREATE TABLE IF NOT EXISTS social_maquina_uso (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    maquina_id      bigint NOT NULL REFERENCES social_maquinas(id) ON DELETE CASCADE,
    usuario_id      integer NOT NULL,
    trabalho_id     uuid NOT NULL REFERENCES social_trabalhos(id) ON DELETE CASCADE,
    em              timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_social_maquina_uso_maquina ON social_maquina_uso (maquina_id, em DESC);

-- social_renders.maquina_id (R13) passa a apontar para a máquina. NOT VALID: não confere linhas antigas, só as novas.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_social_renders_maquina'
                    AND conrelid = to_regclass('social_renders')) THEN
        ALTER TABLE social_renders ADD CONSTRAINT fk_social_renders_maquina
            FOREIGN KEY (maquina_id) REFERENCES social_maquinas(id) NOT VALID;
    END IF;
END $$;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['social_maquinas', 'social_pareamentos', 'social_trabalhos', 'social_maquina_uso']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = t AND policyname = 'social_por_loja'
                        AND schemaname = current_schema()) THEN
            EXECUTE format($p$
                CREATE POLICY social_por_loja ON %I
                    USING (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
                    WITH CHECK (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
            $p$, t);
        END IF;
    END LOOP;
END $$;

INSERT INTO delivery_tracking_schema_versions (version)
VALUES ('20261208_05_social_fila_maquinas')
ON CONFLICT (version) DO NOTHING;

COMMIT;
