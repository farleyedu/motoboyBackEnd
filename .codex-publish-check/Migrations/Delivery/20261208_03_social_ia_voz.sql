-- Zippy Social R10: o minimo da camada de IA (README do Social, secao 2 "IA: cota da Zippy ou chave propria", e secao 9) e o
-- servico de voz. A fase 2 (transcricao, analise de cortes) cresce em cima destas tabelas sem refazer.
--   social_provedores        catalogo global (mantido pela Gestao, sem loja e sem RLS): capacidades, modelos, vozes e precos
--   social_chaves            chave propria da loja, cifrada com TokenProtector; so final4 volta para a tela
--   social_config_ia         por uso: origem (zippy, propria, local), provedor, chave, modelo e o que fazer se a chave falhar
--   social_creditos          creditos do mes (concedidos pelo plano, comprados, usados) e o aviso de 80%
--   social_uso_ia            registro unico de uso: cota, tela "Uso" do cliente e conta da Zippy
--   social_voz_cache         fala ja gerada (hash de texto+voz+vel+provedor+modelo): repetir nao cobra de novo
--   social_voz_consentimentos prova de autorizacao da voz clonada (quem, quando, IP, termo, hash do audio) e a revogacao
-- Tabelas da loja com row-level security igual a 20261208_01 (zippy.loja / zippy.sistema). Idempotente.
BEGIN;

CREATE TABLE IF NOT EXISTS social_provedores (
    id              text PRIMARY KEY,
    nome            text NOT NULL,
    tipo_api        text NOT NULL DEFAULT 'nativo' CHECK (tipo_api IN ('nativo', 'openai_compat')),
    base_url_padrao text,
    capacidades     text[] NOT NULL DEFAULT '{}',   -- transcricao, texto, visao, voz, voz_clone, alinhamento
    modelos         jsonb NOT NULL DEFAULT '{}'::jsonb,
    precos          jsonb NOT NULL DEFAULT '{}'::jsonb,
    ativo           boolean NOT NULL DEFAULT TRUE,
    atualizado_em   timestamptz NOT NULL DEFAULT NOW()
);

