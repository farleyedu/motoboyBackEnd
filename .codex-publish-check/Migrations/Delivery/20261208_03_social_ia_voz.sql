CREATE TABLE IF NOT EXISTS social_chaves (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    provedor_id     text NOT NULL REFERENCES social_provedores(id),
    chave_cifrada   text NOT NULL,
    final4          text NOT NULL,
    base_url        text,                 -- Azure: https://<regiao>.tts.speech.microsoft.com; compativel com OpenAI: endereco proprio
    status          text NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'recusada', 'sem_saldo')),
    testada_em      timestamptz,
    criada_por      integer,
    criada_em       timestamptz NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_chaves_loja_provedor ON social_chaves (estabelecimento_id, provedor_id);

CREATE TABLE IF NOT EXISTS social_config_ia (
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    uso             text NOT NULL CHECK (uso IN ('transcricao', 'analise', 'textos', 'traducao', 'objetivo', 'voz', 'voz_clone', 'roteiro')),
    origem          text NOT NULL DEFAULT 'zippy' CHECK (origem IN ('zippy', 'propria', 'local')),
    provedor_id     text REFERENCES social_provedores(id),
    chave_id        bigint REFERENCES social_chaves(id) ON DELETE SET NULL,
    modelo          text,
    ao_falhar       text NOT NULL DEFAULT 'usar_cota' CHECK (ao_falhar IN ('usar_cota', 'local', 'parar')),
    limite_mes_reais numeric(10,2),
    atualizado_por  integer,
    atualizado_em   timestamptz NOT NULL DEFAULT NOW(),
    PRIMARY KEY (estabelecimento_id, uso)
);

CREATE TABLE IF NOT EXISTS social_creditos (
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    mes             date NOT NULL CHECK (EXTRACT(DAY FROM mes) = 1),
    concedidos      integer NOT NULL DEFAULT 0 CHECK (concedidos >= 0),
    comprados       integer NOT NULL DEFAULT 0 CHECK (comprados >= 0),
    usados          integer NOT NULL DEFAULT 0 CHECK (usados >= 0),
    aviso_80_enviado boolean NOT NULL DEFAULT FALSE,
    PRIMARY KEY (estabelecimento_id, mes),
    CONSTRAINT ck_social_creditos_saldo CHECK (usados <= concedidos + comprados)
);

CREATE TABLE IF NOT EXISTS social_uso_ia (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    usuario_id      integer,
    uso             text NOT NULL,
    provedor_id     text,
    modelo          text,
    origem          text NOT NULL CHECK (origem IN ('zippy', 'propria', 'local')),
    unidades        numeric(12,2) NOT NULL DEFAULT 0,
    unidade         text NOT NULL DEFAULT 'chamada',   -- segundos, caracteres, tokens, chamada
    creditos        integer NOT NULL DEFAULT 0 CHECK (creditos >= 0),
    custo_estimado  numeric(12,6) NOT NULL DEFAULT 0,  -- US$
    corte_id        bigint,
    trabalho_id     bigint,                            -- social_trabalhos chega com a fila (R14)
    detalhe         jsonb NOT NULL DEFAULT '{}'::jsonb,
    em              timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_social_uso_ia_loja ON social_uso_ia (estabelecimento_id, em DESC);

CREATE TABLE IF NOT EXISTS social_voz_cache (
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    hash            text NOT NULL CHECK (hash ~ '^[0-9a-f]{64}$'),
    arquivo_id      uuid NOT NULL REFERENCES social_arquivos(id) ON DELETE CASCADE,
    duracao         numeric(10,2) NOT NULL,
    palavras        jsonb NOT NULL DEFAULT '[]'::jsonb,
    palavras_estimadas boolean NOT NULL DEFAULT TRUE,
    provedor_id     text NOT NULL,
    criado_em       timestamptz NOT NULL DEFAULT NOW(),
    PRIMARY KEY (estabelecimento_id, hash)
);

CREATE TABLE IF NOT EXISTS social_voz_consentimentos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    usuario_id      integer NOT NULL,
    provedor_id     text NOT NULL,
    voz_externa_id  text,
    status          text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'ativa', 'falhou', 'revogada')),
    termo_versao    text NOT NULL,
    termo_texto     text NOT NULL,
    texto_lido      text NOT NULL,
    ip              text,
    user_agent      text,
    audio_sha256    text NOT NULL CHECK (audio_sha256 ~ '^[0-9a-f]{64}$'),
    audio_bytes     bigint NOT NULL,
    audio_duracao   numeric(10,2) NOT NULL,
    aceito_em       timestamptz NOT NULL DEFAULT NOW(),
    erro            text,
    revogado_em     timestamptz,
    revogado_por    integer
);
-- Uma voz ativa (ou sendo criada) por pessoa. A prova fica guardada mesmo depois de revogada.
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_voz_consentimentos_ativa ON social_voz_consentimentos (estabelecimento_id, usuario_id)
    WHERE status IN ('pendente', 'ativa');

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['social_chaves', 'social_config_ia', 'social_creditos', 'social_uso_ia', 'social_voz_cache',
                             'social_voz_consentimentos']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = t AND policyname = 'social_por_loja'
                        AND schemaname = current_schema()) THEN
            EXECUTE format($p$
                CREATE POLICY social_por_loja ON %I
                    USING (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
                    WITH CHECK (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
            $p$, t);
        END IF;
    END LOOP;
END $$;

