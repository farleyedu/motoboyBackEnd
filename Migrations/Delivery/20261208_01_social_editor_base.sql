-- Zippy Social R01: base do editor. Videos e cortes (o minimo para o editor abrir antes do Estudio), receitas versionadas com
-- historico das 30 ultimas, arquivos pequenos guardados no R2 (marca d'agua, som importado, fala gravada ou gerada).
-- Tudo com estabelecimento_id e row-level security: o backend abre transacao e faz
--   SELECT set_config('zippy.loja', '<uuid da loja>', true)
-- (ou set_config('zippy.sistema', 'sim', true) no servico de limpeza). Sem isso as tabelas aparecem vazias.
-- Idempotente.
BEGIN;

CREATE TABLE IF NOT EXISTS social_videos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    titulo          text NOT NULL,
    duracao         numeric(10,2) NOT NULL DEFAULT 0,
    resolucao       text,
    eh_gta          boolean NOT NULL DEFAULT FALSE,
    maquina_id      bigint,               -- social_maquinas entra no prompt das maquinas
    caminho_local   text,
    previa_key      text,
    miniatura_key   text,
    exemplo         boolean NOT NULL DEFAULT FALSE,
    criado_por      integer,
    criado_em       timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_social_videos_loja ON social_videos (estabelecimento_id, criado_em DESC);

CREATE TABLE IF NOT EXISTS social_cortes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    video_id        bigint NOT NULL REFERENCES social_videos(id) ON DELETE CASCADE,
    ini             numeric(10,2) NOT NULL,
    fim             numeric(10,2) NOT NULL,
    titulo          text NOT NULL DEFAULT '',
    nota_regras     integer,
    momento_forte_s numeric(10,2),
    decisao         text CHECK (decisao IN ('usar', 'talvez', 'descartar')),
    ordem           integer NOT NULL DEFAULT 0,
    miniatura_key   text,
    previa_key      text,
    dados           jsonb NOT NULL DEFAULT '{}'::jsonb,   -- DadosCorte do motor (R02): momentos, falas, minimapa, ext
    criado_em       timestamptz NOT NULL DEFAULT NOW(),
    atualizado_em   timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_social_cortes_tempo CHECK (fim > ini AND ini >= 0)
);
CREATE INDEX IF NOT EXISTS ix_social_cortes_video ON social_cortes (video_id, ordem);
CREATE INDEX IF NOT EXISTS ix_social_cortes_loja ON social_cortes (estabelecimento_id);

CREATE TABLE IF NOT EXISTS social_receitas (
    corte_id        bigint PRIMARY KEY REFERENCES social_cortes(id) ON DELETE CASCADE,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    versao          integer NOT NULL CHECK (versao >= 1),
    receita         jsonb NOT NULL,
    atualizado_por  integer,
    atualizado_em   timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_social_receitas_loja ON social_receitas (estabelecimento_id);

CREATE TABLE IF NOT EXISTS social_receitas_historico (
    corte_id        bigint NOT NULL REFERENCES social_cortes(id) ON DELETE CASCADE,
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    versao          integer NOT NULL,
    receita         jsonb NOT NULL,
    quem            integer,
    em              timestamptz NOT NULL DEFAULT NOW(),
    PRIMARY KEY (corte_id, versao)
);
CREATE INDEX IF NOT EXISTS ix_social_receitas_historico_loja ON social_receitas_historico (estabelecimento_id);

CREATE TABLE IF NOT EXISTS social_arquivos (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    estabelecimento_id uuid NOT NULL REFERENCES estabelecimentos(id) ON DELETE CASCADE,
    dono_usuario_id integer NOT NULL,
    tipo            text NOT NULL CHECK (tipo IN ('imagem', 'audio', 'video')),
    nome            text NOT NULL,
    mime            text NOT NULL,
    bytes           bigint NOT NULL CHECK (bytes > 0),
    duracao         numeric(10,2),
    largura         integer,
    altura          integer,
    r2_key          text NOT NULL,
    origem          text NOT NULL DEFAULT 'upload' CHECK (origem IN ('upload', 'voz_ia', 'gravacao')),
    hash_sha256     text NOT NULL,
    criado_em       timestamptz NOT NULL DEFAULT NOW(),
    enviado_em      timestamptz,          -- preenchido no /confirmar; sem isso o envio nao terminou
    apagar_em       timestamptz           -- envio nao confirmado expira em 1 dia; apagado pelo dono = agora
);
CREATE INDEX IF NOT EXISTS ix_social_arquivos_loja ON social_arquivos (estabelecimento_id, criado_em DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_social_arquivos_hash ON social_arquivos (estabelecimento_id, hash_sha256)
    WHERE apagar_em IS NULL;
CREATE INDEX IF NOT EXISTS ix_social_arquivos_apagar ON social_arquivos (apagar_em) WHERE apagar_em IS NOT NULL;

-- Row-level security por loja. FORCE para valer tambem para o dono das tabelas (o usuario do backend).
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['social_videos', 'social_cortes', 'social_receitas', 'social_receitas_historico', 'social_arquivos']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = t AND policyname = 'social_por_loja'
                        AND schemaname = current_schema()) THEN
            EXECUTE format($p$
                CREATE POLICY social_por_loja ON %I
                    USING (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
                    WITH CHECK (COALESCE(current_setting('zippy.sistema', true), '') = 'sim'
                           OR estabelecimento_id::text = COALESCE(current_setting('zippy.loja', true), ''))
            $p$, t);
        END IF;
    END LOOP;
END $$;

INSERT INTO delivery_tracking_schema_versions (version)
VALUES ('20261208_01_social_editor_base')
ON CONFLICT (version) DO NOTHING;

COMMIT;
